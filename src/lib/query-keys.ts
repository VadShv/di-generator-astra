// Централизованная фабрика ключей React Query для сгенерированных ДИ и должностей.
//
// Три пути генерации ДИ (вкладка «Генерация ДИ», карточка должности в штатном
// расписании, массовая генерация) пишут в одни и те же таблицы БД
// (GeneratedDI.positionId), но исторически читали данные независимыми
// useState-стейтами без общего кэша. Единые ключи позволяют читать данные из
// одного кэша React Query и инвалидировать их сразу для всех экранов после
// генерации/удаления/смены статуса, откуда бы операция ни была запущена.

/** Ключи для сгенерированных ДИ. */
export const diKeys = {
  /** Корень для инвалидации всех ДИ-запросов сразу. */
  all: ['generated-di'] as const,
  /** Полный список ДИ (вкладка «Генерация ДИ»). */
  list: () => [...diKeys.all, 'list'] as const,
  /** Список ДИ конкретной должности (карточка должности). */
  byPosition: (positionId: string) => [...diKeys.all, 'by-position', positionId] as const,
}

/** Ключи для должностей (дерево штатного расписания со статус-бейджами ДИ). */
export const positionKeys = {
  /** Корень для инвалидации всех запросов должностей. */
  all: ['positions'] as const,
  /** Список должностей (с включёнными generatedDIs для бейджей статуса). */
  list: () => [...positionKeys.all, 'list'] as const,
}
