async function main() {
  let created = 0
  let skipped = 0

  for (const ref of SEED_REFS) {
    const existing = await db.legalReference.findFirst({ where: { article: ref.article } })
    if (existing) {
      console.log(`  → ${ref.article} — уже существует, пропуск`)
      skipped++
      continue
    }
    await db.legalReference.create({ data: ref })
    console.log(`  ✓ ${ref.article} — создан`)
    created++
  }

  console.log(`\nГотово. Создано: ${created}, пропущено: ${skipped}`)
  await db.$disconnect()
}

main().catch((e) => {
  console.error('Ошибка:', e)
  process.exit(1)
})
