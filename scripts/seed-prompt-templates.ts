async function main() {
  let created = 0
  let skipped = 0

  for (const prompt of SEED_PROMPTS) {
    const existing = await db.masterPrompt.findFirst({ where: { name: prompt.name } })
    if (existing) {
      console.log(`  → ${prompt.name} — уже существует, пропуск`)
      skipped++
      continue
    }
    await db.masterPrompt.create({ data: { ...prompt, version: 1, variables: '[]' } })
    console.log(`  ✓ ${prompt.name} — создан`)
    created++
  }

  console.log(`\nГотово. Создано: ${created}, пропущено: ${skipped}`)
  await db.$disconnect()
}

main().catch((e) => {
  console.error('Ошибка:', e)
  process.exit(1)
})
